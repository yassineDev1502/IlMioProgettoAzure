app.MapGet("/api/config-check", (IConfiguration config) =>
{
    var dbString = config["ConnectionStrings:DefaultConnection"];
    var apiKey = config["ExternalServices:ApiKey"];

    return Results.Ok(new
    {
        DatabaseString = dbString,
        ExtApiKey = apiKey,
        Environment = Environment.GetEnvironmentVariable("ASPNETCORE_ENVIRONMENT") ?? "Not Set"
    });
});


